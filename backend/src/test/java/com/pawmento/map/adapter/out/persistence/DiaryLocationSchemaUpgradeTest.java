package com.pawmento.map.adapter.out.persistence;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.List;
import java.util.Map;
import java.util.UUID;

import javax.sql.DataSource;

import org.hibernate.boot.Metadata;
import org.hibernate.boot.MetadataSources;
import org.hibernate.boot.model.naming.CamelCaseToUnderscoresNamingStrategy;
import org.hibernate.boot.registry.StandardServiceRegistry;
import org.hibernate.boot.registry.StandardServiceRegistryBuilder;
import org.hibernate.cfg.AvailableSettings;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.annotation.Import;
import org.springframework.jdbc.core.JdbcTemplate;

import com.pawmento.TestcontainersConfiguration;

// 이미 위치 행이 있는 옛 diary_location 테이블(출처·revision 열이 생기기 전)에, 앱이 쓰는 것과 같은 Hibernate 스키마 업데이트(ddl-auto update)가
// 새 열을 안전하게 더하는지 확인한다. 실제 테이블을 건드리지 않도록 임시 스키마에 옛 테이블을 만들어 같은 엔티티로 업데이트한다.
// 진짜 PostgreSQL에서 확인한다
@Import(TestcontainersConfiguration.class)
@SpringBootTest(properties = "pawmento.auth.jwt-secret=test-only-jwt-secret-0123456789-abcdefghij")
class DiaryLocationSchemaUpgradeTest {

	@Autowired
	private DataSource dataSource;

	@Autowired
	private JdbcTemplate jdbcTemplate;

	private String schema;

	@BeforeEach
	void createLegacyTable() {
		schema = "legacy_" + UUID.randomUUID().toString().replace("-", "");
		jdbcTemplate.execute("create schema " + schema);
		// 출처·revision 열이 없던 시절의 테이블
		jdbcTemplate.execute("""
				create table %s.diary_location (
					id bigint generated by default as identity primary key,
					diary_id bigint not null,
					pet_id bigint not null,
					created_by bigint not null,
					latitude double precision not null,
					longitude double precision not null,
					place_name varchar(255),
					created_at timestamp(6) with time zone not null,
					updated_at timestamp(6) with time zone not null,
					constraint uk_diary_location_diary unique (diary_id)
				)
				""".formatted(schema));
		jdbcTemplate.update("""
				insert into %s.diary_location (diary_id, pet_id, created_by, latitude, longitude, place_name, created_at, updated_at)
				values (1, 10, 100, 37.5, 127.0, '강남역', now(), now()), (2, 10, 100, 35.1, 129.0, null, now(), now())
				""".formatted(schema));
	}

	@AfterEach
	void dropLegacyTable() {
		jdbcTemplate.execute("drop schema if exists " + schema + " cascade");
	}

	// 앱의 ddl-auto update를 이 엔티티로 임시 스키마에 실행한다
	private void runSchemaUpdate() {
		StandardServiceRegistry registry = new StandardServiceRegistryBuilder()
			.applySetting(AvailableSettings.JAKARTA_NON_JTA_DATASOURCE, dataSource)
			.applySetting(AvailableSettings.DEFAULT_SCHEMA, schema)
			.applySetting(AvailableSettings.PHYSICAL_NAMING_STRATEGY,
					CamelCaseToUnderscoresNamingStrategy.class.getName())
			// 앱 설정(spring.jpa.hibernate.ddl-auto: update)과 같은 방식이다. 세션 팩토리를 만들 때 스키마가 업데이트된다
			.applySetting(AvailableSettings.HBM2DDL_AUTO, "update")
			.build();
		try {
			Metadata metadata = new MetadataSources(registry).addAnnotatedClass(DiaryLocationJpaEntity.class)
				.buildMetadata();
			metadata.buildSessionFactory().close();
		}
		finally {
			StandardServiceRegistryBuilder.destroy(registry);
		}
	}

	private List<Map<String, Object>> sourceColumns() {
		return jdbcTemplate.queryForList("""
				select column_name, is_nullable, column_default
				from information_schema.columns
				where table_schema = ? and table_name = 'diary_location'
				  and column_name in ('source', 'source_asset_id', 'source_revision')
				order by column_name
				""", schema);
	}

	@Test
	@DisplayName("#44-S13 행이 이미 있는 옛 테이블에 출처·revision 열이 추가되고, 기존 행은 MANUAL·출처 자산 없음·revision 0으로 채워진다")
	void existingRowsAreBackfilled() {
		assertThat(sourceColumns()).isEmpty();

		runSchemaUpdate();

		List<Map<String, Object>> columns = sourceColumns();
		assertThat(columns).extracting(column -> column.get("column_name"))
			.containsExactly("source", "source_asset_id", "source_revision");
		assertThat(columns.get(0).get("is_nullable")).isEqualTo("NO");
		assertThat(columns.get(1).get("is_nullable")).isEqualTo("YES");
		assertThat(columns.get(2).get("is_nullable")).isEqualTo("NO");
		List<Map<String, Object>> rows = jdbcTemplate.queryForList(
				"select diary_id, place_name, source, source_asset_id, source_revision from %s.diary_location order by diary_id"
					.formatted(schema));
		assertThat(rows).hasSize(2);
		for (Map<String, Object> row : rows) {
			assertThat(row.get("source")).isEqualTo("MANUAL");
			assertThat(row.get("source_asset_id")).isNull();
			assertThat(((Number) row.get("source_revision")).longValue()).isZero();
		}
		// 기존 값은 그대로다
		assertThat(rows.get(0).get("place_name")).isEqualTo("강남역");
		assertThat(rows.get(1).get("place_name")).isNull();
	}

	@Test
	@DisplayName("#44-S13 스키마 업데이트를 다시 실행해도 오류가 없고, 그사이 바뀐 revision과 기존 데이터를 옛 값으로 덮지 않는다")
	void reRunKeepsUserValues() {
		runSchemaUpdate();
		jdbcTemplate.update("update %s.diary_location set source_revision = 7 where diary_id = 1".formatted(schema));
		jdbcTemplate.update("""
				insert into %s.diary_location (diary_id, pet_id, created_by, latitude, longitude, created_at, updated_at, source_revision)
				values (3, 10, 100, 36.0, 128.0, now(), now(), 3)
				""".formatted(schema));

		runSchemaUpdate();

		Map<Object, Object> revisions = new java.util.HashMap<>();
		jdbcTemplate.queryForList("select diary_id, source_revision from %s.diary_location".formatted(schema))
			.forEach(row -> revisions.put(row.get("diary_id"), row.get("source_revision")));
		assertThat(((Number) revisions.get(1L)).longValue()).isEqualTo(7L);
		assertThat(((Number) revisions.get(2L)).longValue()).isZero();
		assertThat(((Number) revisions.get(3L)).longValue()).isEqualTo(3L);
		assertThat(sourceColumns()).hasSize(3);
	}

	@Test
	@DisplayName("#44-S13 새 열의 기본값이 남아 있어, 출처와 revision을 모르는 옛 방식의 삽입도 실패하지 않는다")
	void defaultsKeepOldStyleInsertsWorking() {
		runSchemaUpdate();

		jdbcTemplate.update("""
				insert into %s.diary_location (diary_id, pet_id, created_by, latitude, longitude, created_at, updated_at)
				values (9, 10, 100, 36.0, 128.0, now(), now())
				""".formatted(schema));

		Map<String, Object> row = jdbcTemplate.queryForMap(
				"select source, source_revision from %s.diary_location where diary_id = 9".formatted(schema));
		assertThat(row.get("source")).isEqualTo("MANUAL");
		assertThat(((Number) row.get("source_revision")).longValue()).isZero();
	}

}
